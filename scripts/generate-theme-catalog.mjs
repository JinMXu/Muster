#!/usr/bin/env node
// Generates src-tauri/src/theme/catalog_ghostty.rs from the Ghostty theme
// files in mbadolato/iTerm2-Color-Schemes (ghostty/ directory).
//
// Usage: node scripts/generate-theme-catalog.mjs [source-dir]
//
// With `source-dir`, reads Ghostty theme files from that local directory
// (e.g. a sparse clone of the repo — handy when the GitHub API rate limit
// is exhausted). Without it, lists the directory via the GitHub contents API
// and downloads each file (8 concurrent, via curl).
//
// Parses the Ghostty `key = value` format, derives the app's extra fields
// (accent/sidebar/divider and any missing palette/cursor/selection entries),
// and emits a static Rust table.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import path from "node:path";
import { fileURLToPath } from "node:url";

const execFileAsync = promisify(execFile);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src-tauri", "src", "theme", "catalog_ghostty.rs");
const API = "https://api.github.com/repos/mbadolato/iTerm2-Color-Schemes/contents/ghostty";
const CONCURRENCY = 8;

// ---- color helpers (hex without '#') -------------------------------------

function hexToRgb(hex) {
  const h = hex.replace(/^#/, "");
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

function rgbToHex([r, g, b]) {
  const c = (v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0");
  return c(r) + c(g) + c(b);
}

/** Mix `hex` toward `target` by `t` (0..1). */
function mix(hex, target, t) {
  const a = hexToRgb(hex);
  const b = hexToRgb(target);
  return rgbToHex(a.map((v, i) => v + (b[i] - v) * t));
}

const darken = (hex, t) => mix(hex, "000000", t);
const lighten = (hex, t) => mix(hex, "ffffff", t);

// ---- ghostty file parsing -------------------------------------------------

// Default ANSI palette used to back-fill missing indices 0..7.
const FALLBACK_PALETTE = [
  "000000", "cc0000", "4e9a06", "c4a000", "3465a4", "75507b", "06989a", "d3d7cf",
  "555753", "ef2929", "8ae234", "fce94f", "729fcf", "ad7fa8", "34e2e2", "eeeeec",
];

function parseGhostty(text) {
  const palette = new Map();
  const fields = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1).trim();
    if (key === "palette") {
      const m = value.match(/^(\d+)\s*=\s*(#[0-9a-fA-F]{6})$/);
      if (m) palette.set(Number(m[1]), m[2].slice(1).toLowerCase());
    } else if (/^#[0-9a-fA-F]{6}$/.test(value)) {
      fields[key] = value.slice(1).toLowerCase();
    }
  }
  return { palette, fields };
}

function toTheme(name, { palette, fields }) {
  const background = fields["background"] ?? "000000";
  const foreground = fields["foreground"] ?? "ffffff";

  // Back-fill any missing palette slots: 0..7 from a sane default, 8..15 as
  // a brightened copy of the matching 0..7 entry.
  const pal = [];
  for (let i = 0; i < 16; i++) {
    pal.push(
      palette.get(i) ??
        (i < 8 ? FALLBACK_PALETTE[i] : lighten(palette.get(i - 8) ?? FALLBACK_PALETTE[i - 8], 0.2))
    );
  }

  return {
    name,
    background,
    foreground,
    cursor: fields["cursor-color"] ?? foreground,
    accent: pal[4], // blue
    selection_bg: fields["selection-background"] ?? mix(background, foreground, 0.2),
    selection_fg: fields["selection-foreground"] ?? foreground,
    sidebar: darken(background, 0.3),
    divider: palette.has(8) ? pal[8] : lighten(background, 0.2),
    palette: pal,
  };
}

// ---- rust codegen ---------------------------------------------------------

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

function emitRust(themes) {
  const lines = [];
  lines.push("//! Generated by scripts/generate-theme-catalog.mjs from the Ghostty");
  lines.push("//! themes in mbadolato/iTerm2-Color-Schemes. Do not edit by hand.");
  lines.push("//!");
  lines.push(`//! ${themes.length} themes, sorted alphabetically by name.`);
  lines.push("");
  lines.push("use super::ThemeColors;");
  lines.push("");
  lines.push("/// A catalog entry with static strings; converted to `ThemeColors` on lookup.");
  lines.push("pub struct StaticTheme {");
  lines.push("    pub name: &'static str,");
  lines.push("    pub background: &'static str,");
  lines.push("    pub foreground: &'static str,");
  lines.push("    pub cursor: &'static str,");
  lines.push("    pub accent: &'static str,");
  lines.push("    pub selection_bg: &'static str,");
  lines.push("    pub selection_fg: &'static str,");
  lines.push("    pub sidebar: &'static str,");
  lines.push("    pub divider: &'static str,");
  lines.push("    pub palette: [&'static str; 16],");
  lines.push("}");
  lines.push("");
  lines.push("impl StaticTheme {");
  lines.push("    pub fn to_colors(&self) -> ThemeColors {");
  lines.push("        ThemeColors {");
  lines.push("            name: self.name.into(),");
  lines.push("            background: self.background.into(),");
  lines.push("            foreground: self.foreground.into(),");
  lines.push("            cursor: self.cursor.into(),");
  lines.push("            accent: self.accent.into(),");
  lines.push("            selection_bg: self.selection_bg.into(),");
  lines.push("            selection_fg: self.selection_fg.into(),");
  lines.push("            sidebar: self.sidebar.into(),");
  lines.push("            divider: self.divider.into(),");
  lines.push("            palette: self.palette.map(str::to_owned),");
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  lines.push("pub static THEMES: &[StaticTheme] = &[");
  for (const t of themes) {
    lines.push("    StaticTheme {");
    for (const k of ["name", "background", "foreground", "cursor", "accent", "selection_bg", "selection_fg", "sidebar", "divider"]) {
      lines.push(`        ${k}: "${esc(t[k])}",`);
    }
    lines.push("        palette: [");
    for (let i = 0; i < 16; i += 4) {
      lines.push(`            ${t.palette.slice(i, i + 4).map((c) => `"${c}"`).join(", ")},`);
    }
    lines.push("        ],");
    lines.push("    },");
  }
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

// ---- main -----------------------------------------------------------------

// curl is used instead of node fetch — undici proved flaky against GitHub
// from this network (stalled TLS sockets), curl is reliable.
async function fetchText(url, label) {
  let lastErr;
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const { stdout } = await execFileAsync("curl", [
        "-sfL", "--retry", "3", "--connect-timeout", "15", "--max-time", "60", url,
      ], { maxBuffer: 16 * 1024 * 1024 });
      return stdout;
    } catch (err) {
      lastErr = err;
      await new Promise((r) => setTimeout(r, 500 * (attempt + 1)));
    }
  }
  throw new Error(`${label}: ${lastErr.message}`);
}

async function listFiles() {
  const out = [];
  for (let page = 1; ; page++) {
    const items = JSON.parse(await fetchText(`${API}?per_page=100&page=${page}`, `GitHub API page ${page}`));
    if (!Array.isArray(items) || items.length === 0) break;
    for (const it of items) {
      if (it.type === "file" && it.download_url) out.push({ name: it.name, url: it.download_url });
    }
    if (items.length < 100) break;
  }
  return out;
}

async function downloadAll(files) {
  let done = 0;
  const run = async () => {
    for (;;) {
      const f = files[done++];
      if (!f) return;
      f.text = await fetchText(f.url, `download ${f.name}`);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, run));
}

const SOURCE_DIR = process.argv[2] ? path.resolve(process.argv[2]) : null;

const files = SOURCE_DIR
  ? await Promise.all(
      (await readdir(SOURCE_DIR))
        .filter((name) => !name.startsWith("."))
        .map(async (name) => ({ name, text: await readFile(path.join(SOURCE_DIR, name), "utf8") }))
    )
  : await listFiles().then(async (listed) => {
      console.log(`listed ${listed.length} theme files`);
      await downloadAll(listed);
      return listed;
    });
const themes = files
  .map((f) => toTheme(f.name, parseGhostty(f.text)))
  .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" }));
await writeFile(OUT, emitRust(themes), "utf8");
console.log(`wrote ${themes.length} themes to ${path.relative(ROOT, OUT)}`);
